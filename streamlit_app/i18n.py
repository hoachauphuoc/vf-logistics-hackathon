def init_language():
    """Initialize language selector in sidebar. Call at top of each page."""
    if 'lang' not in st.session_state:
        st.session_state.lang = "EN"
    
    langs = ["EN", "VN", "JA"]
    labels = {"EN": "🇬🇧 English", "VN": "🇻🇳 Tiếng Việt", "JA": "🇯🇵 日本語"}
    
    selected = st.sidebar.selectbox(
        "🌐",
        langs,
        index=langs.index(st.session_state.lang),
        format_func=lambda x: labels[x],
        key="lang_selector"
    )
    st.session_state.lang = selected
    return TRANSLATIONS[selected]

def translate_dynamic(session, text, target_lang):
    """Layer 2: Translate dynamic AI-generated content using Cortex TRANSLATE.
    Only call for dynamic content (AI results, alerts), not for static UI."""
    if target_lang == "EN" or not text:
        return text
    
    lang_map = {"VN": "vi", "JA": "ja"}
    target = lang_map.get(target_lang, "en")
    
    safe_text = text.replace("'", "''")
    try:
        result = session.sql(f"SELECT SNOWFLAKE.CORTEX.TRANSLATE('{safe_text}', 'en', '{target}')").collect()[0][0]
        return result
    except:
        return text


