END';
CREATE OR REPLACE PROCEDURE "WORKFLOW_INVESTIGATE_ANOMALY"("P_ALERT_ID" NUMBER(38,0))
RETURNS VARCHAR
LANGUAGE SQL
COMMENT='AI-powered fraud investigation: analyzes BL patterns, compares with historical data, generates risk assessment report with recommended actions.'
EXECUTE AS CALLER
AS 'DECLARE
    v_alert_type VARCHAR;
    v_bl_id NUMBER;
    v_description VARCHAR;
    v_bl_number VARCHAR;
    v_shipper VARCHAR;
    v_consignee VARCHAR;
    v_charges NUMBER;
    v_weight NUMBER;
    v_carrier VARCHAR;
    v_port_load VARCHAR;
    v_port_discharge VARCHAR;
    v_ai_analysis VARCHAR;
    v_context VARCHAR;
BEGIN
    -- Step 1: Get alert details
    SELECT ALERT_TYPE, BL_ID, DESCRIPTION 
    INTO :v_alert_type, :v_bl_id, :v_description
    FROM MENDIX_APP.AGENTS.FRAUD_ALERT WHERE ALERT_ID = :P_ALERT_ID;

    -- Step 2: Get shipment context
    SELECT BL_NUMBER, SHIPPER_NAME, CONSIGNEE_NAME, TOTAL_CHARGES, GROSS_WEIGHT_KGS, CARRIER_NAME, PORT_OF_LOADING_LOCODE, PORT_OF_DISCHARGE_LOCODE
    INTO :v_bl_number, :v_shipper, :v_consignee, :v_charges, :v_weight, :v_carrier, :v_port_load, :v_port_discharge
    FROM MENDIX_APP.AGENTS.BILL_OF_LADING WHERE BL_ID = :v_bl_id;

    -- Step 3: Build context for AI
    v_context := ''Alert: '' || :v_alert_type || ''. BL: '' || :v_bl_number || ''. Shipper: '' || :v_shipper || ''. Consignee: '' || :v_consignee || ''. Charges: $'' || NVL(TO_VARCHAR(:v_charges),''N/A'') || ''. Weight: '' || NVL(TO_VARCHAR(:v_weight),''N/A'') || ''kg. Carrier: '' || :v_carrier || ''. Route: '' || :v_port_load || '' -> '' || :v_port_discharge;

    -- Step 4: AI analysis using Cortex
    SELECT SNOWFLAKE.CORTEX.COMPLETE(''mistral-large2'', 
        ''You are a maritime logistics fraud analyst. Analyze this alert and provide: 1) Risk assessment (HIGH/MEDIUM/LOW), 2) Key suspicious indicators, 3) Recommended action (BLOCK/ESCALATE/CLEAR). Be concise.\\n\\nAlert context: '' || :v_context
    ) INTO :v_ai_analysis;

    -- Step 5: Update alert status to INVESTIGATING
    UPDATE MENDIX_APP.AGENTS.FRAUD_ALERT SET STATUS = ''INVESTIGATING'' WHERE ALERT_ID = :P_ALERT_ID;

    RETURN ''{"workflow":"INVESTIGATE_ANOMALY","alert_id":'' || :P_ALERT_ID || '',"bl_number":"'' || :v_bl_number || ''","alert_type":"'' || :v_alert_type || ''","context":"'' || REPLACE(:v_context, ''"'', ''\\\\"'') || ''","ai_analysis":'' || :v_ai_analysis || ''}'';
END';
CREATE OR REPLACE PROCEDURE "WORKFLOW_SANCTIONS_SCREEN"("P_ENTITY_NAME" VARCHAR)
RETURNS VARCHAR
LANGUAGE SQL
COMMENT='Screens entity names against sanctions lists using AI fuzzy matching. Returns risk level and matching details for compliance review.'
EXECUTE AS CALLER
AS 'DECLARE
    v_match_count NUMBER DEFAULT 0;
    v_result VARCHAR;
BEGIN
    SELECT COUNT(*) INTO :v_match_count
    FROM SNOWFLAKE_PUBLIC_DATA_FREE.PUBLIC_DATA_FREE.INTERNATIONAL_TRADE_ADMINISTRATION_EXPORT_SCREENED_ENTITIES_INDEX
    WHERE UPPER(EXPORT_RESTRICTED_ENTITY_NAME) LIKE ''%'' || UPPER(:P_ENTITY_NAME) || ''%'';

    IF (:v_match_count > 0) THEN
        v_result := ''{"workflow":"SANCTIONS_SCREEN","entity":"'' || :P_ENTITY_NAME || ''","matches_found":'' || :v_match_count || '',"risk_level":"CRITICAL","action":"BLOCK - Entity appears on US Government Consolidated Screening List (Snowflake Marketplace data)"}'';
    ELSE
        v_result := ''{"workflow":"SANCTIONS_SCREEN","entity":"'' || :P_ENTITY_NAME || ''","matches_found":0,"risk_level":"CLEAR","action":"No matches on screening lists. Entity cleared for trade."}'';
    END IF;

    RETURN :v_result;
END';
