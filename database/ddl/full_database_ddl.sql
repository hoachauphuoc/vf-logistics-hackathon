        SELECT EXCHANGE_RATE INTO V_TO_RATE
        FROM V_EXCHANGE_RATES WHERE QUOTE_CURRENCY_ID = :P_TO LIMIT 1;
    END IF;
    
    -- Convert: FROM -> USD -> TO
    V_CONVERTED := (:P_AMOUNT / V_FROM_RATE) * V_TO_RATE;
    
    RETURN OBJECT_CONSTRUCT(
        ''from'', P_FROM,
        ''to'', P_TO,
        ''amount'', P_AMOUNT,
        ''rate'', ROUND(V_TO_RATE / V_FROM_RATE, 6),
