create or replace view V_AI_DAILY_COST(
	DAY,
	TOTAL_CALLS,
	TOTAL_TOKENS,
	INPUT_TOKENS,
	OUTPUT_TOKENS,
	AVG_LATENCY_MS,
	ESTIMATED_COST_USD,
	ERRORS
) as
SELECT 
    DATE(CALL_TIMESTAMP) as DAY,
    COUNT(*) as TOTAL_CALLS,
    SUM(TOTAL_TOKENS) as TOTAL_TOKENS,
    SUM(CASE WHEN TOTAL_TOKENS IS NOT NULL THEN TOTAL_TOKENS * 0.6 / 1000000 ELSE 0 END) as INPUT_TOKENS,
    SUM(CASE WHEN TOTAL_TOKENS IS NOT NULL THEN TOTAL_TOKENS * 0.4 / 1000000 ELSE 0 END) as OUTPUT_TOKENS,
    ROUND(AVG(DATEDIFF('SECOND', CALL_TIMESTAMP, CALL_TIMESTAMP)) * 1000, 0) as AVG_LATENCY_MS,
    ROUND(SUM(COALESCE(TOTAL_TOKENS, 0)) * 0.0000015, 6) as ESTIMATED_COST_USD,
    SUM(CASE WHEN CALL_STATUS = 'ERROR' THEN 1 ELSE 0 END) as ERRORS
FROM AI_CALL_LOG
GROUP BY DATE(CALL_TIMESTAMP);
create or replace view V_AI_USAGE_SUMMARY(
	PROCEDURE_NAME,
	CALL_COUNT,
	TOTAL_TOKENS,
	AVG_LATENCY_MS,
	SUCCESS_COUNT,
	ERROR_COUNT,
	ERROR_RATE_PCT
) as
SELECT 
    CONTEXT as PROCEDURE_NAME,
    COUNT(*) as CALL_COUNT,
    SUM(COALESCE(TOTAL_TOKENS, 0)) as TOTAL_TOKENS,
    ROUND(AVG(DATEDIFF('SECOND', CALL_TIMESTAMP, CALL_TIMESTAMP)) * 1000, 0) as AVG_LATENCY_MS,
    SUM(CASE WHEN CALL_STATUS = 'SUCCESS' THEN 1 ELSE 0 END) as SUCCESS_COUNT,
    SUM(CASE WHEN CALL_STATUS = 'ERROR' THEN 1 ELSE 0 END) as ERROR_COUNT,
    ROUND(SUM(CASE WHEN CALL_STATUS = 'ERROR' THEN 1 ELSE 0 END) * 100.0 / NULLIF(COUNT(*), 0), 1) as ERROR_RATE_PCT
FROM AI_CALL_LOG
GROUP BY CONTEXT;
