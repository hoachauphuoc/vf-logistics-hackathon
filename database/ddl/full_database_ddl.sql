CREATE OR REPLACE PROCEDURE "REVIEW_DOCUMENT"("P_DOC_ID" NUMBER(38,0), "P_ACTION" VARCHAR, "P_REVIEWER" VARCHAR DEFAULT null, "P_NOTES" VARCHAR DEFAULT null, "P_CORRECTIONS" VARCHAR DEFAULT null)
RETURNS VARCHAR
LANGUAGE SQL
COMMENT='Core MVP: Human-in-the-loop review for AI-extracted documents. Actions: APPROVE (mark as verified), REJECT (flag for re-processing), CORRECT (update 4 key fields from corrections JSON, set confidence=100, sync to SAP).'
EXECUTE AS OWNER
AS 'BEGIN
    LET current_status VARCHAR;
