CREATE OR REPLACE PROCEDURE "GET_EXCHANGE_RATE"("P_FROM" VARCHAR, "P_TO" VARCHAR, "P_AMOUNT" FLOAT)
RETURNS VARIANT
LANGUAGE SQL
EXECUTE AS OWNER
AS '
DECLARE
    V_FROM_RATE FLOAT DEFAULT 1.0;
    V_TO_RATE FLOAT DEFAULT 1.0;
    V_CONVERTED FLOAT;
    V_RATE_DATE DATE;
BEGIN
    -- Get rate for source currency (if not USD)
    IF (:P_FROM != ''USD'') THEN
        SELECT EXCHANGE_RATE, RATE_DATE INTO V_FROM_RATE, V_RATE_DATE
        FROM V_EXCHANGE_RATES WHERE QUOTE_CURRENCY_ID = :P_FROM LIMIT 1;
