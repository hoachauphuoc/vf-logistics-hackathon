CREATE OR REPLACE PROCEDURE MENDIX_APP.AGENTS.AI_GENERATE_INSIGHTS("P_LANGUAGE" VARCHAR DEFAULT 'EN')
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS '
DECLARE
    V_TOTAL_BLS NUMBER;
    V_HIGH_RISK NUMBER;
    V_SAP_POSTED NUMBER;
    V_AVG_CHARGES FLOAT;
    V_OPEN_ALERTS NUMBER;
    V_STATS VARCHAR;
    V_PROMPT VARCHAR;
    V_RAW VARCHAR;
    V_INSIGHTS VARCHAR;
    V_START_POS NUMBER;
    V_END_POS NUMBER;
    V_START_TS TIMESTAMP_NTZ;
    V_ELAPSED_MS NUMBER;
    V_CALL_STATUS VARCHAR;
    V_IN_TOKENS NUMBER;
    V_OUT_TOKENS NUMBER;
BEGIN
    SELECT
        COUNT(*),
        SUM(CASE WHEN STATUS = ''Pending_Review'' THEN 1 ELSE 0 END),
        SUM(CASE WHEN STATUS = ''SAP_POSTED'' THEN 1 ELSE 0 END),
        ROUND(AVG(TOTAL_CHARGES), 2)
    INTO V_TOTAL_BLS, V_HIGH_RISK, V_SAP_POSTED, V_AVG_CHARGES
    FROM BILL_OF_LADING;

    SELECT COUNT(*) INTO V_OPEN_ALERTS FROM FRAUD_ALERT WHERE STATUS = ''OPEN'';

    V_STATS := ''Total BLs: '' || :V_TOTAL_BLS || '', Pending: '' || :V_HIGH_RISK ||
               '', SAP Posted: '' || :V_SAP_POSTED || '', Avg charges: $'' || :V_AVG_CHARGES ||
               '', Open fraud alerts: '' || :V_OPEN_ALERTS;

    V_PROMPT := ''Return ONLY a JSON object (no markdown, no explanation). Stats: '' || :V_STATS ||
                ''. Format: {"status":"SUCCESS","insights":[{"category":"RISK","priority":"HIGH","title":"...","insight":"..."},{"category":"OPPORTUNITY","priority":"MEDIUM","title":"...","insight":"..."},{"category":"TREND","priority":"LOW","title":"...","insight":"..."}],"data_summary":"..."}'';

    V_START_TS := CURRENT_TIMESTAMP();

    BEGIN
        SELECT SNOWFLAKE.CORTEX.COMPLETE(''llama3-8b'', :V_PROMPT) INTO V_RAW;
        V_CALL_STATUS := ''SUCCESS'';

        V_START_POS := POSITION(''{'' IN V_RAW);
        V_END_POS := LENGTH(V_RAW) - POSITION(''}'' IN REVERSE(V_RAW)) + 1;

        IF (V_START_POS > 0 AND V_END_POS > V_START_POS) THEN
