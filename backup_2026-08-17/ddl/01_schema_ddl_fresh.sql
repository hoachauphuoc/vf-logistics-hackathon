  WHERE DOC_ID = :P_DOC_ID;

  IF (v_file_name IS NULL OR v_file_name = '''') THEN
    RETURN ''{"error":"Document not found"}'';
  END IF;

  -- Still valid with a 2-minute safety buffer -> skip regeneration, reuse the existing URL
  IF (v_existing_url IS NOT NULL AND v_expiry IS NOT NULL AND v_expiry > DATEADD(''MINUTE'', 2, CURRENT_TIMESTAMP())) THEN
    RETURN v_existing_url;
  END IF;

  -- Expired or missing -> regenerate on demand
  LET sql_stmt VARCHAR := ''SELECT GET_PRESIGNED_URL(@MENDIX_APP.AGENTS.LOGISTICS_STAGE, '''''' || :v_file_name || '''''', 3600)'';
  rs := (EXECUTE IMMEDIATE :sql_stmt);
  LET c CURSOR FOR rs;
  OPEN c;
  FETCH c INTO v_url;
  CLOSE c;

  UPDATE MENDIX_APP.AGENTS.BILL_OF_LADING_EXTRACTED
  SET PDF_PRESIGNED_URL = :v_url,
      PDF_URL_EXPIRY = DATEADD(''SECOND'', 3600, CURRENT_TIMESTAMP())
  WHERE DOC_ID = :P_DOC_ID;

  RETURN v_url;
END;
';
