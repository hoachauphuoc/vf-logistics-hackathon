CREATE OR REPLACE PROCEDURE MENDIX_APP.AGENTS.PROCESS_BL_DOCUMENTS()
RETURNS VARCHAR
LANGUAGE SQL
COMMENT='Document intelligence stage: refreshes the stage directory (so files just uploaded with PUT are visible), scans LOGISTICS_STAGE for new PDFs, uses CORTEX.PARSE_DOCUMENT (OCR) + CORTEX.COMPLETE (mistral-large2) to extract identity, commercial and counterparty fields, computes a 4-factor confidence score, generates Alert/AlertResponse via AI_COMPLETE, and inserts into BILL_OF_LADING_EXTRACTED. The commercial fields (shipper, consignee, carrier, freight charges) are what allow SYNC_EXTRACTED_TO_BILL_OF_LADING to feed the fraud pipeline. Errors logged to ERROR_LOG.'
EXECUTE AS OWNER
AS 'BEGIN
    LET processed NUMBER := 0;
    LET errors NUMBER := 0;

    -- A stage directory table does not automatically see files added by PUT, so
    -- refresh it first; without this, a batch upload followed immediately by this
    -- procedure would silently process nothing.
    ALTER STAGE MENDIX_APP.AGENTS.LOGISTICS_STAGE REFRESH;

    LET file_cursor CURSOR FOR (
        SELECT RELATIVE_PATH, SIZE
        FROM DIRECTORY(@MENDIX_APP.AGENTS.LOGISTICS_STAGE)
        WHERE RELATIVE_PATH ILIKE ''%.pdf''
        AND RELATIVE_PATH NOT IN (SELECT FILE_NAME FROM MENDIX_APP.AGENTS.BILL_OF_LADING_EXTRACTED)
    );

    FOR file_rec IN file_cursor DO
        LET rel_path VARCHAR := file_rec.RELATIVE_PATH;
        LET fsize NUMBER := file_rec.SIZE;
        LET start_ts TIMESTAMP_NTZ := CURRENT_TIMESTAMP();

        BEGIN
            LET parsed_text VARCHAR;
            parsed_text := (SELECT SNOWFLAKE.CORTEX.PARSE_DOCUMENT(''@MENDIX_APP.AGENTS.LOGISTICS_STAGE'', :rel_path, {''mode'': ''OCR''}):content::VARCHAR);

            LET prompt VARCHAR := ''Extract fields from this Bill of Lading as valid JSON only. Fields: {"bl_number":"","container_number":"","vessel_name":"","voyage_number":"","carrier_name":"","shipper_name":"","consignee_name":"","notify_party":"","port_of_loading":"","port_of_discharge":"","commodity_desc":"","hs_code":"","gross_weight_kg":0,"net_weight_kg":0,"package_count":0,"package_type":"","freight_charges":0,"freight_currency":"USD","eta":"YYYY-MM-DD","date_of_issue":"YYYY-MM-DD","anomalies":[]}. Use null when a field is genuinely absent from the document; never invent a value. freight_charges must be the numeric total freight amount only, with no currency symbol or thousands separator. Return ONLY JSON. Text: '' || LEFT(:parsed_text, 8000);

            LET extracted_json VARCHAR;
            extracted_json := (SELECT SNOWFLAKE.CORTEX.COMPLETE(''mistral-large2'', :prompt));

            LET json_start NUMBER := POSITION(''{'' IN :extracted_json);
            LET json_end NUMBER := LENGTH(:extracted_json) - POSITION(''}'' IN REVERSE(:extracted_json)) + 1;
            IF (:json_start > 0 AND :json_end > :json_start) THEN
                extracted_json := SUBSTRING(:extracted_json, :json_start, :json_end - :json_start + 1);
            END IF;

            LET parsed VARIANT := TRY_PARSE_JSON(:extracted_json);
            IF (:parsed IS NULL) THEN
                parsed := PARSE_JSON(''{"bl_number":null,"container_number":null,"vessel_name":null,"gross_weight_kg":0}'');
            END IF;

            LET v_bl VARCHAR := :parsed:bl_number::VARCHAR;
            LET v_container VARCHAR := :parsed:container_number::VARCHAR;
            LET v_vessel VARCHAR := :parsed:vessel_name::VARCHAR;
            LET v_voyage VARCHAR := :parsed:voyage_number::VARCHAR;
            LET v_carrier VARCHAR := :parsed:carrier_name::VARCHAR;
            LET v_shipper VARCHAR := :parsed:shipper_name::VARCHAR;
            LET v_consignee VARCHAR := :parsed:consignee_name::VARCHAR;
            LET v_notify VARCHAR := :parsed:notify_party::VARCHAR;
            LET v_pol VARCHAR := :parsed:port_of_loading::VARCHAR;
            LET v_pod VARCHAR := :parsed:port_of_discharge::VARCHAR;
            LET v_commodity VARCHAR := :parsed:commodity_desc::VARCHAR;
            LET v_hs VARCHAR := :parsed:hs_code::VARCHAR;
            LET v_weight FLOAT := :parsed:gross_weight_kg::FLOAT;
            LET v_net_weight FLOAT := :parsed:net_weight_kg::FLOAT;
            LET v_pkg_count NUMBER := TRY_CAST(:parsed:package_count::VARCHAR AS NUMBER);
            LET v_pkg_type VARCHAR := :parsed:package_type::VARCHAR;
            LET v_freight FLOAT := TRY_CAST(REGEXP_REPLACE(:parsed:freight_charges::VARCHAR, ''[^0-9.]'', '''') AS FLOAT);
            LET v_currency VARCHAR := NVL(:parsed:freight_currency::VARCHAR, ''USD'');
            LET v_date DATE := TRY_CAST(:parsed:date_of_issue::VARCHAR AS DATE);
            LET v_json VARCHAR := :extracted_json;

            LET key_ok NUMBER := 0;
            IF (:v_container IS NOT NULL AND LENGTH(:v_container) >= 8 AND :v_container NOT LIKE ''%@%'' AND :v_container NOT LIKE ''XXXX%'' AND :v_container NOT LIKE ''%#%'' AND :v_container NOT LIKE ''%$%'') THEN key_ok := :key_ok + 1; END IF;
            IF (:v_vessel IS NOT NULL AND LENGTH(TRIM(:v_vessel)) > 2) THEN key_ok := :key_ok + 1; END IF;
            IF (:v_weight IS NOT NULL AND :v_weight > 0 AND :v_weight < 100000) THEN key_ok := :key_ok + 1; END IF;
            IF (:v_date IS NOT NULL AND :v_date >= ''2025-01-01'') THEN key_ok := :key_ok + 1; END IF;

            LET confidence FLOAT := :key_ok * 25.0;
            LET doc_status VARCHAR := IFF(:confidence >= 85, ''AI_Processed'', ''Pending_Review'');
            LET elapsed NUMBER := TIMESTAMPDIFF(''MILLISECOND'', :start_ts, CURRENT_TIMESTAMP());

            LET alert_prompt VARCHAR := ''Evaluate this Bill of Lading record against EXACTLY these 4 rules and NOTHING else. Do not apply any other business judgment, plausibility check, or numeric threshold beyond what is written. 1) ContainerNumber INVALID only if: null, OR length<8, OR contains @ # $, OR starts with "XXXX". 2) VesselName INVALID only if: null OR trimmed length<=2. 3) GrossWeightKg INVALID only if: null OR value<=0 OR value>=100000 (any value strictly between 0 and 100000 is VALID, no matter how small). 4) DateOfIssue INVALID only if: null OR earlier than 2025-01-01 (any date on/after 2025-01-01 is VALID, no matter how far in the future). Record: ContainerNumber='' || COALESCE(:v_container,''(null)'') || '', VesselName='' || COALESCE(:v_vessel,''(null)'') || '', GrossWeightKg='' || COALESCE(TO_VARCHAR(:v_weight),''(null)'') || '', DateOfIssue='' || COALESCE(TO_VARCHAR(:v_date),''(null)'') || ''. Output ONLY a single raw JSON object, nothing before or after it, no reasoning, no markdown, no backticks. JSON has exactly two keys: "Alert" (if zero rules violated, exactly "No anomalies detected"; else short semicolon list of violated rule names only) and "AlertResponse" (if zero rules violated, exactly "Document passed all validation checks."; else 1-2 sentences citing only the violated rule(s) and actual value).'';

            LET alert_raw VARCHAR := (SELECT AI_COMPLETE(''claude-sonnet-4-5'', :alert_prompt));
            alert_raw := REGEXP_REPLACE(:alert_raw, ''^```json\\s*|\\s*```$'', '''');
            LET alert_parsed VARIANT := TRY_PARSE_JSON(:alert_raw);
            LET v_alert VARCHAR := :alert_parsed:"Alert"::VARCHAR;
            LET v_alert_response VARCHAR := :alert_parsed:"AlertResponse"::VARCHAR;

            INSERT INTO MENDIX_APP.AGENTS.BILL_OF_LADING_EXTRACTED (
                FILE_NAME, FILE_PATH, FILE_SIZE_BYTES,
                BL_NUMBER, CONTAINER_NUMBER, VESSEL_NAME, VOYAGE_NUMBER, CARRIER_NAME,
                SHIPPER_NAME, CONSIGNEE_NAME, NOTIFY_PARTY,
                PORT_OF_LOADING, PORT_OF_DISCHARGE,
                COMMODITY_DESC, HS_CODE,
                GROSS_WEIGHT_KG, NET_WEIGHT_KG, PACKAGE_COUNT, PACKAGE_TYPE,
                FREIGHT_CHARGES, FREIGHT_CURRENCY, DATE_OF_ISSUE,
                CONFIDENCE_SCORE, STATUS, RAW_EXTRACTED_JSON, RAW_TEXT, AI_MODEL_USED, PROCESSING_TIME_MS, PROCESSED_AT,
                ALERT, ALERT_RESPONSE
            )
            SELECT :rel_path, ''@MENDIX_APP.AGENTS.LOGISTICS_STAGE/'' || :rel_path, :fsize,
                :v_bl, :v_container, :v_vessel, :v_voyage, :v_carrier,
                :v_shipper, :v_consignee, :v_notify,
                :v_pol, :v_pod,
                :v_commodity, :v_hs,
                :v_weight, :v_net_weight, :v_pkg_count, :v_pkg_type,
                :v_freight, :v_currency, :v_date,
                :confidence, :doc_status, TRY_PARSE_JSON(:v_json), LEFT(:parsed_text, 30000), ''mistral-large2'', :elapsed, CURRENT_TIMESTAMP(),
                :v_alert, :v_alert_response;

            processed := :processed + 1;
        EXCEPTION
            WHEN OTHER THEN
                errors := :errors + 1;
                INSERT INTO MENDIX_APP.AGENTS.ERROR_LOG (PROCEDURE_NAME, FILE_NAME, ERROR_CODE, ERROR_MESSAGE)
                SELECT ''PROCESS_BL_DOCUMENTS'', :rel_path, :SQLSTATE, :SQLERRM;
        END;
    END FOR;

    RETURN ''Complete. Processed: '' || :processed::VARCHAR || '' | Errors: '' || :errors::VARCHAR;
END';
