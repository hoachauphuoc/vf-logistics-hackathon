CREATE OR REPLACE PROCEDURE MENDIX_APP.AGENTS.GET_OR_REFRESH_PDF_URL("P_DOC_ID" NUMBER(38,0))
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS '
