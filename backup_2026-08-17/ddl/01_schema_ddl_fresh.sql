CREATE OR REPLACE PROCEDURE MENDIX_APP.AGENTS.GET_PDF_URL("P_DOC_ID" NUMBER(38,0))
RETURNS VARCHAR
LANGUAGE SQL
COMMENT='Generates presigned S3 URL (1hr expiry) for PDF viewing in Mendix. Checks PDF_URL_EXPIRY first: skips regeneration and reuses the existing URL if it still has more than 2 minutes left, otherwise regenerates on demand. This means any normal call from Mendix (which already auto-resumes the warehouse) also keeps the URL fresh, with no separate scheduled task needed.'
EXECUTE AS OWNER
AS '
DECLARE
  v_file_name VARCHAR;
  v_expiry TIMESTAMP_NTZ;
  v_existing_url VARCHAR;
  v_url VARCHAR;
