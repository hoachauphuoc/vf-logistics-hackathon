CREATE OR REPLACE PROCEDURE MENDIX_APP.AGENTS.AI_COMPLETE_WITH_RETRY("P_PROMPT" VARCHAR, "P_MODEL" VARCHAR DEFAULT 'llama3-8b', "P_MAX_RETRIES" NUMBER(38,0) DEFAULT 2)
RETURNS VARIANT
LANGUAGE SQL
COMMENT='Wrapper for CORTEX.COMPLETE with retry logic. Handles transient AI model failures gracefully with configurable retry count.'
EXECUTE AS OWNER
AS 'BEGIN
    DECLARE
        V_RESPONSE VARIANT;
        V_RESPONSE_TEXT VARCHAR;
        V_RETRY_COUNT NUMBER DEFAULT 0;
        V_ERROR_MSG VARCHAR;
        V_MODEL_TO_USE VARCHAR DEFAULT P_MODEL;
    BEGIN
        WHILE (V_RETRY_COUNT <= P_MAX_RETRIES) DO
            BEGIN
                V_RESPONSE := (SELECT SNOWFLAKE.CORTEX.COMPLETE(:V_MODEL_TO_USE, :P_PROMPT));
                V_RESPONSE_TEXT := (SELECT TO_VARCHAR(:V_RESPONSE));

                INSERT INTO AI_CALL_LOG (MODEL_NAME, PROMPT, RESPONSE, CALL_STATUS, CONTEXT)
                VALUES (:V_MODEL_TO_USE, :P_PROMPT, :V_RESPONSE_TEXT, ''SUCCESS'', ''AI_COMPLETE_WITH_RETRY'');

                RETURN V_RESPONSE;
            EXCEPTION
                WHEN OTHER THEN
                    V_ERROR_MSG := SQLERRM;
                    V_RETRY_COUNT := V_RETRY_COUNT + 1;

                    IF (V_RETRY_COUNT = 1 AND V_MODEL_TO_USE = ''llama3-8b'') THEN
                        V_MODEL_TO_USE := ''mistral-large2'';
                    END IF;

                    INSERT INTO AI_CALL_LOG (MODEL_NAME, PROMPT, CALL_STATUS, ERROR_MESSAGE, CONTEXT)
                    VALUES (:V_MODEL_TO_USE, :P_PROMPT, ''ERROR'', :V_ERROR_MSG, ''AI_COMPLETE_WITH_RETRY'');

                    IF (V_RETRY_COUNT > P_MAX_RETRIES) THEN
                        RETURN OBJECT_CONSTRUCT(''error'', TRUE, ''message'', V_ERROR_MSG);
                    END IF;
            END;
        END WHILE;

        RETURN OBJECT_CONSTRUCT(''error'', TRUE, ''message'', ''Max retries exceeded'');
    END;
END';
