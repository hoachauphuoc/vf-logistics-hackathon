    LET current_status VARCHAR;
    current_status := (SELECT STATUS FROM MENDIX_APP.AGENTS.BILL_OF_LADING_EXTRACTED WHERE DOC_ID = :P_DOC_ID);
    
    IF (:current_status IS NULL) THEN
        RETURN ''{"error":"Document not found"}'';
    END IF;
    
    IF (:P_ACTION = ''APPROVE'') THEN
        UPDATE MENDIX_APP.AGENTS.BILL_OF_LADING_EXTRACTED
        SET STATUS = ''Synced_To_SAP'',
            FINAL_STATUS = ''APPROVED'',
            REVIEWED_BY = COALESCE(:P_REVIEWER, CURRENT_USER()::VARCHAR),
            REVIEWED_AT = CURRENT_TIMESTAMP(),
            REVIEW_NOTES = :P_NOTES,
            CONFIDENCE_SCORE = 100
        WHERE DOC_ID = :P_DOC_ID;
        
    ELSEIF (:P_ACTION = ''REJECT'') THEN
        UPDATE MENDIX_APP.AGENTS.BILL_OF_LADING_EXTRACTED
        SET FINAL_STATUS = ''REJECTED'',
            REVIEWED_BY = COALESCE(:P_REVIEWER, CURRENT_USER()::VARCHAR),
            REVIEWED_AT = CURRENT_TIMESTAMP(),
            REVIEW_NOTES = :P_NOTES
        WHERE DOC_ID = :P_DOC_ID;
        
    ELSEIF (:P_ACTION = ''CORRECT'') THEN
        LET corrections VARIANT := TRY_PARSE_JSON(:P_CORRECTIONS);
        
        IF (:corrections IS NOT NULL) THEN
            UPDATE MENDIX_APP.AGENTS.BILL_OF_LADING_EXTRACTED
            SET CONTAINER_NUMBER = COALESCE(:corrections:container_number::VARCHAR, CONTAINER_NUMBER),
                VESSEL_NAME = COALESCE(:corrections:vessel_name::VARCHAR, VESSEL_NAME),
                GROSS_WEIGHT_KG = COALESCE(:corrections:gross_weight_kg::FLOAT, GROSS_WEIGHT_KG),
                DATE_OF_ISSUE = COALESCE(TRY_CAST(:corrections:arrival_date::VARCHAR AS DATE), DATE_OF_ISSUE),
                STATUS = ''Synced_To_SAP'',
                FINAL_STATUS = ''CORRECTED'',
                CONFIDENCE_SCORE = 100,
                REVIEWED_BY = COALESCE(:P_REVIEWER, CURRENT_USER()::VARCHAR),
                REVIEWED_AT = CURRENT_TIMESTAMP(),
                REVIEW_NOTES = :P_NOTES,
                CORRECTED_JSON = :corrections
            WHERE DOC_ID = :P_DOC_ID;
        ELSE
            RETURN ''{"error":"Invalid corrections JSON format"}'';
        END IF;
    ELSE
        RETURN ''{"error":"Invalid action. Use APPROVE, REJECT, or CORRECT"}'';
    END IF;
    
    RETURN ''{"status":"success","action":"'' || :P_ACTION || ''","doc_id":'' || :P_DOC_ID::VARCHAR || ''}'';
END';
