CREATE OR REPLACE PROCEDURE MENDIX_APP.AGENTS.GET_EXCHANGE_RATE("P_FROM" VARCHAR, "P_TO" VARCHAR, "P_AMOUNT" FLOAT)
RETURNS VARIANT
LANGUAGE SQL
EXECUTE AS OWNER
AS '
DECLARE
    V_FROM_RATE FLOAT DEFAULT 1.0;
    V_TO_RATE FLOAT DEFAULT 1.0;
    V_CONVERTED FLOAT;
    V_RATE_DATE DATE;
