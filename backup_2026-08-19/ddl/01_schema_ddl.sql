                REVIEWED_AT = CURRENT_TIMESTAMP(), REVIEW_NOTES = :P_NOTES, CORRECTED_JSON = :corrections
            WHERE DOC_ID = :P_DOC_ID;
        ELSE RETURN ''{"error":"Invalid corrections JSON format"}''; END IF;
    ELSE RETURN ''{"error":"Invalid action. Use APPROVE, REJECT, or CORRECT"}''; END IF;
