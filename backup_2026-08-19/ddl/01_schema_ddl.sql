CREATE OR REPLACE PROCEDURE MENDIX_APP.AGENTS.REVIEW_DOCUMENT("P_DOC_ID" NUMBER(38,0), "P_ACTION" VARCHAR, "P_REVIEWER" VARCHAR DEFAULT null, "P_NOTES" VARCHAR DEFAULT null, "P_CORRECTIONS" VARCHAR DEFAULT null)
RETURNS VARCHAR
LANGUAGE SQL
COMMENT='Human-in-the-loop review for AI-extracted documents. Actions: APPROVE, REJECT, CORRECT.'
EXECUTE AS OWNER
AS 'BEGIN
    LET current_status VARCHAR;
    current_status := (SELECT STATUS FROM MENDIX_APP.AGENTS.BILL_OF_LADING_EXTRACTED WHERE DOC_ID = :P_DOC_ID);
    IF (:current_status IS NULL) THEN RETURN ''{"error":"Document not found"}''; END IF;
    IF (:P_ACTION = ''APPROVE'') THEN
        UPDATE MENDIX_APP.AGENTS.BILL_OF_LADING_EXTRACTED
        SET STATUS = ''Synced_To_SAP'', FINAL_STATUS = ''APPROVED'',
            REVIEWED_BY = COALESCE(:P_REVIEWER, CURRENT_USER()::VARCHAR),
            REVIEWED_AT = CURRENT_TIMESTAMP(), REVIEW_NOTES = :P_NOTES, CONFIDENCE_SCORE = 100
