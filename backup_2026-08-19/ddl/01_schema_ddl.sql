CREATE OR REPLACE PROCEDURE MENDIX_APP.AGENTS.WORKFLOW_INVESTIGATE_ANOMALY("P_ALERT_ID" NUMBER(38,0))
RETURNS VARCHAR
LANGUAGE SQL
COMMENT='AI investigation: builds evidence pack, uses structured JSON output to decide BLOCK/ESCALATE/CLEAR.'
EXECUTE AS CALLER
AS '
DECLARE
    v_alert_type VARCHAR; v_bl_id NUMBER; v_bl_number VARCHAR; v_shipper VARCHAR; v_consignee VARCHAR;
    v_charges NUMBER; v_weight NUMBER; v_carrier VARCHAR; v_port_load VARCHAR; v_port_discharge VARCHAR;
    v_confidence FLOAT; v_cost_per_kg FLOAT; v_median_cpk FLOAT; v_p95_cpk FLOAT;
    v_cpk_multiple FLOAT; v_cpk_band VARCHAR; v_band_rule VARCHAR;
    v_sanction_hits NUMBER DEFAULT 0; v_doc_context VARCHAR DEFAULT '''';
    v_prompt VARCHAR; v_resp VARIANT; v_payload VARIANT; v_context VARCHAR;
    v_decision VARCHAR; v_reason VARCHAR; v_assessment VARCHAR;
    v_start_ts TIMESTAMP_NTZ; v_elapsed_ms NUMBER;
    v_in_tok NUMBER DEFAULT 0; v_out_tok NUMBER DEFAULT 0; v_tot_tok NUMBER DEFAULT 0;
    v_attempts NUMBER DEFAULT 0; v_contract VARCHAR; v_options VARIANT;
BEGIN
    SELECT ALERT_TYPE, BL_ID INTO :v_alert_type, :v_bl_id FROM MENDIX_APP.AGENTS.FRAUD_ALERT WHERE ALERT_ID = :P_ALERT_ID LIMIT 1;
    SELECT BL_NUMBER, SHIPPER_NAME, CONSIGNEE_NAME, TOTAL_CHARGES, GROSS_WEIGHT_KGS, CARRIER_NAME,
           PORT_OF_LOADING_LOCODE, PORT_OF_DISCHARGE_LOCODE, AI_CONFIDENCE_SCORE
    INTO :v_bl_number, :v_shipper, :v_consignee, :v_charges, :v_weight, :v_carrier, :v_port_load, :v_port_discharge, :v_confidence
    FROM MENDIX_APP.AGENTS.BILL_OF_LADING WHERE BL_ID = :v_bl_id LIMIT 1;
    v_cost_per_kg := ROUND(:v_charges / NULLIF(:v_weight, 0), 4);
    SELECT ROUND(MEDIAN(TOTAL_CHARGES / NULLIF(GROSS_WEIGHT_KGS,0)),4),
           ROUND(PERCENTILE_CONT(0.95) WITHIN GROUP (ORDER BY TOTAL_CHARGES / NULLIF(GROSS_WEIGHT_KGS,0)),4)
    INTO :v_median_cpk, :v_p95_cpk FROM MENDIX_APP.AGENTS.BILL_OF_LADING
    WHERE TOTAL_CHARGES IS NOT NULL AND GROSS_WEIGHT_KGS > 0;
    v_cpk_multiple := ROUND(:v_cost_per_kg / NULLIF(:v_median_cpk, 0), 2);
    v_cpk_band := CASE WHEN :v_cpk_multiple IS NULL THEN ''NOT_COMPUTABLE''
        WHEN :v_cpk_multiple > 10 THEN ''EXTREME_ABOVE_10X_MEDIAN''
        WHEN :v_cpk_multiple > 5 THEN ''ELEVATED_BETWEEN_5X_AND_10X_MEDIAN''
        ELSE ''NORMAL_AT_OR_BELOW_5X_MEDIAN'' END;
    v_band_rule := CASE :v_cpk_band
        WHEN ''EXTREME_ABOVE_10X_MEDIAN'' THEN ''Mandates BLOCK on economics alone.''
        WHEN ''ELEVATED_BETWEEN_5X_AND_10X_MEDIAN'' THEN ''Mandates ESCALATE for human judgement.''
        WHEN ''NORMAL_AT_OR_BELOW_5X_MEDIAN'' THEN ''Economically ordinary, does NOT justify BLOCK or ESCALATE alone.''
        ELSE ''Not computable, reason to ESCALATE.'' END;
    BEGIN
        SELECT COUNT(*) INTO :v_sanction_hits FROM MENDIX_APP.AGENTS.V_SANCTIONS_SCREENING_SOURCE
        WHERE UPPER(ENTITY_NAME) LIKE ''%'' || UPPER(NVL(:v_shipper, ''~none~'')) || ''%''
           OR UPPER(ENTITY_NAME) LIKE ''%'' || UPPER(NVL(:v_consignee, ''~none~'')) || ''%'';
    EXCEPTION WHEN OTHER THEN v_sanction_hits := -1; END;
    BEGIN
        SELECT '' DOCUMENT PROVENANCE: extracted from PDF '' || e.FILE_NAME || ''. Confidence '' || COALESCE(e.CONFIDENCE_SCORE::VARCHAR, ''unknown'') || ''/100. Alert: '' || COALESCE(e.ALERT, ''not recorded'')
        INTO :v_doc_context FROM MENDIX_APP.AGENTS.BILL_OF_LADING_EXTRACTED e WHERE e.BL_ID = :v_bl_id LIMIT 1;
    EXCEPTION WHEN OTHER THEN v_doc_context := ''''; END;
    v_context := ''Alert type: '' || :v_alert_type || ''. BL: '' || :v_bl_number || ''. Shipper: '' || NVL(:v_shipper, ''(not stated)'') || ''. Consignee: '' || NVL(:v_consignee, ''(not stated)'') || ''. Route: '' || NVL(:v_port_load, ''?'') || '' -> '' || NVL(:v_port_discharge, ''?'') || ''. Charges: $'' || NVL(TO_VARCHAR(:v_charges),''n/a'') || ''. Weight: '' || NVL(TO_VARCHAR(:v_weight),''n/a'') || ''kg. Cost/kg: $'' || NVL(TO_VARCHAR(:v_cost_per_kg),''n/a'') || '' ('' || NVL(TO_VARCHAR(:v_cpk_multiple),''n/a'') || ''x median $'' || :v_median_cpk || ''). BAND: '' || :v_cpk_band || ''. '' || :v_band_rule || '' Sanctions matches: '' || :v_sanction_hits || ''.'' || NVL(:v_doc_context, '''');
    v_prompt := ''You are a maritime logistics fraud analyst. The cost-per-kg band is PRE-COMPUTED. Trust it. Rubric: BLOCK if sanctions>0, OR band is EXTREME, OR counterparty is suspicious/shell/unknown. ESCALATE if band is ELEVATED, OR cost not computable, OR extraction confidence<60. CLEAR if sanctions=0 AND band NORMAL AND counterparties are real businesses. Return JSON: {"decision":"BLOCK|ESCALATE|CLEAR","reason":"...","assessment":"..."}. Evidence: '' || :v_context;
    v_contract := ''{"type":"json","schema":{"type":"object","properties":{"decision":{"type":"string","enum":["BLOCK","ESCALATE","CLEAR"]},"reason":{"type":"string"},"assessment":{"type":"string"}},"required":["decision","reason","assessment"]}}'';
    v_options := PARSE_JSON(''{"temperature":0,"max_tokens":700,"response_format":'' || :v_contract || ''}'');
    WHILE (:v_attempts < 2 AND :v_decision IS NULL) DO
        v_attempts := :v_attempts + 1;
        v_start_ts := CURRENT_TIMESTAMP();
        BEGIN
            SELECT SNOWFLAKE.CORTEX.COMPLETE(''mistral-large2'', ARRAY_CONSTRUCT(OBJECT_CONSTRUCT(''role'', ''user'', ''content'', :v_prompt)), :v_options) INTO :v_resp;
            v_elapsed_ms := DATEDIFF(''millisecond'', :v_start_ts, CURRENT_TIMESTAMP());
            v_in_tok := NVL(:v_resp:usage:prompt_tokens::NUMBER, 0);
            v_out_tok := NVL(:v_resp:usage:completion_tokens::NUMBER, 0);
            v_tot_tok := NVL(:v_resp:usage:total_tokens::NUMBER, :v_in_tok + :v_out_tok);
            v_payload := TRY_PARSE_JSON(:v_resp:structured_output[0]:raw_message::STRING);
            v_decision := UPPER(NVL(:v_payload:decision::STRING, ''''));
            IF (:v_decision NOT IN (''BLOCK'', ''ESCALATE'', ''CLEAR'')) THEN v_decision := NULL; END IF;
            v_reason := :v_payload:reason::STRING;
            v_assessment := :v_payload:assessment::STRING;
            INSERT INTO MENDIX_APP.AGENTS.AI_CALL_LOG (CALL_TIMESTAMP, MODEL_NAME, PROCEDURE_NAME, CONTEXT, CALL_STATUS, STATUS, LATENCY_MS, INPUT_TOKENS, OUTPUT_TOKENS, TOTAL_TOKENS, PROMPT, RESPONSE)
            SELECT CURRENT_TIMESTAMP(), ''mistral-large2'', ''WORKFLOW_INVESTIGATE_ANOMALY'', ''fraud_investigation:attempt'' || :v_attempts,
                   IFF(:v_decision IS NULL, ''PARSE_RETRY'', ''SUCCESS''), IFF(:v_decision IS NULL, ''PARSE_RETRY'', ''SUCCESS''),
                   :v_elapsed_ms, :v_in_tok, :v_out_tok, :v_tot_tok, LEFT(:v_prompt, 5000), LEFT(:v_resp:structured_output[0]:raw_message::STRING, 10000);
        EXCEPTION WHEN OTHER THEN
            v_elapsed_ms := DATEDIFF(''millisecond'', :v_start_ts, CURRENT_TIMESTAMP());
            INSERT INTO MENDIX_APP.AGENTS.AI_CALL_LOG (CALL_TIMESTAMP, MODEL_NAME, PROCEDURE_NAME, CONTEXT, CALL_STATUS, STATUS, LATENCY_MS, PROMPT, RESPONSE)
            SELECT CURRENT_TIMESTAMP(), ''mistral-large2'', ''WORKFLOW_INVESTIGATE_ANOMALY'', ''fraud_investigation:attempt'' || :v_attempts, ''ERROR'', ''ERROR'', :v_elapsed_ms, LEFT(:v_prompt, 5000), LEFT(SQLERRM, 1000);
        END;
    END WHILE;
    IF (:v_decision IS NULL) THEN
        v_decision := ''ESCALATE''; v_reason := ''AI could not return a valid decision; routed to human review.'';
        v_assessment := NVL(:v_assessment, ''No assessment returned.'');
    END IF;
    UPDATE MENDIX_APP.AGENTS.FRAUD_ALERT SET STATUS = ''INVESTIGATING'', AI_RISK_ASSESSMENT = :v_assessment,
        AI_RECOMMENDED_ACTION = :v_decision, AI_DECISION_REASON = LEFT(:v_reason, 2000), AI_ANALYZED_AT = CURRENT_TIMESTAMP()
    WHERE ALERT_ID = :P_ALERT_ID;
    RETURN ''{"workflow":"INVESTIGATE_ANOMALY","alert_id":'' || :P_ALERT_ID || '',"ai_decision":"'' || :v_decision || ''","sanctions_matches":'' || :v_sanction_hits || '',"band":"'' || :v_cpk_band || ''"}'';
END
';
