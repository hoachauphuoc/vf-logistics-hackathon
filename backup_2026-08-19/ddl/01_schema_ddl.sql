            V_INSIGHTS := ''{"status":"SUCCESS","insights":[{"category":"RISK","priority":"HIGH","title":"Pending Backlog","insight":"'' || :V_HIGH_RISK || '' pending shipments need review"}],"data_summary":"'' || :V_STATS || ''"}'';
    END;
    V_ELAPSED_MS := DATEDIFF(''millisecond'', :V_START_TS, CURRENT_TIMESTAMP());
    V_IN_TOKENS := CEIL(LENGTH(:V_PROMPT) / 4.0);
