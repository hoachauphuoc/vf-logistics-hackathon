    CALL MENDIX_APP.AGENTS.WORKFLOW_AUTO_REMEDIATE(:v_alert_id, ''ESCALATE'');
    RETURN ''{"workflow":"FULL_PIPELINE","status":"COMPLETED","alert_investigated":'' || :v_alert_id || ''}'';
END';
CREATE OR REPLACE PROCEDURE MENDIX_APP.AGENTS.WORKFLOW_FULL_PIPELINE_V2("P_MODE" VARCHAR DEFAULT 'AUTO', "P_MAX_ALERTS" NUMBER(38,0) DEFAULT 1)
RETURNS VARCHAR
LANGUAGE SQL
COMMENT='End-to-end automation: detect -> investigate -> sanctions -> remediate -> SAP post for cleared.'
EXECUTE AS CALLER
AS '
DECLARE
    v_start_time TIMESTAMP; v_step_start TIMESTAMP; v_step_ms NUMBER;
    v_alert_id NUMBER; v_severity VARCHAR; v_prev_alert_id NUMBER DEFAULT NULL;
    v_shipper VARCHAR; v_sap_bl_id NUMBER; v_sap_result VARCHAR; v_elapsed_ms NUMBER;
    v_ai_action VARCHAR; v_ai_reason VARCHAR;
    v_processed NUMBER DEFAULT 0; v_blocked NUMBER DEFAULT 0; v_escalated NUMBER DEFAULT 0;
    v_cleared NUMBER DEFAULT 0; v_sap_posted NUMBER DEFAULT 0;
    v_first_decision VARCHAR DEFAULT NULL; v_first_reason VARCHAR DEFAULT NULL;
    v_alert_ids VARCHAR DEFAULT ''''; v_max NUMBER;
BEGIN
    v_start_time := CURRENT_TIMESTAMP();
    v_max := GREATEST(NVL(:P_MAX_ALERTS, 1), 1);
    v_step_start := CURRENT_TIMESTAMP();
    CALL MENDIX_APP.AGENTS.WORKFLOW_DETECT_AND_ACT();
    v_step_ms := DATEDIFF(''millisecond'', :v_step_start, CURRENT_TIMESTAMP());
    INSERT INTO MENDIX_APP.AGENTS.WORKFLOW_AUDIT_LOG (WORKFLOW_NAME, STEP_NAME, STEP_ORDER, INPUT_PARAMS, OUTPUT_RESULT, EXECUTION_TIME_MS, STATUS)
    VALUES (''FULL_PIPELINE_V2'', ''DETECT_ANOMALIES'', 1, :P_MODE || '',max='' || :v_max, ''Scan completed'', :v_step_ms, ''SUCCESS'');
    LOOP
        IF (:v_processed >= :v_max) THEN BREAK; END IF;
        v_alert_id := NULL;
        v_alert_id := (SELECT ALERT_ID FROM MENDIX_APP.AGENTS.FRAUD_ALERT
        WHERE STATUS = ''OPEN'' AND SEVERITY IN (''HIGH'', ''MEDIUM'') AND BL_ID IS NOT NULL
        ORDER BY CASE SEVERITY WHEN ''HIGH'' THEN 1 ELSE 2 END, CREATED_AT DESC LIMIT 1);
        IF (:v_alert_id IS NULL) THEN BREAK; END IF;
        IF (:v_prev_alert_id IS NOT NULL AND :v_alert_id = :v_prev_alert_id) THEN BREAK; END IF;
        v_prev_alert_id := :v_alert_id;
        v_step_start := CURRENT_TIMESTAMP();
        CALL MENDIX_APP.AGENTS.WORKFLOW_INVESTIGATE_ANOMALY(:v_alert_id);
        v_step_ms := DATEDIFF(''millisecond'', :v_step_start, CURRENT_TIMESTAMP());
        SELECT NVL(AI_RECOMMENDED_ACTION, ''ESCALATE''), NVL(AI_DECISION_REASON, ''No AI reason'')
        INTO :v_ai_action, :v_ai_reason FROM MENDIX_APP.AGENTS.FRAUD_ALERT WHERE ALERT_ID = :v_alert_id LIMIT 1;
        INSERT INTO MENDIX_APP.AGENTS.WORKFLOW_AUDIT_LOG (WORKFLOW_NAME, STEP_NAME, STEP_ORDER, INPUT_PARAMS, OUTPUT_RESULT, EXECUTION_TIME_MS, STATUS)
        VALUES (''FULL_PIPELINE_V2'', ''AI_INVESTIGATE'', 2, ''alert='' || :v_alert_id, ''decision='' || :v_ai_action, :v_step_ms, ''SUCCESS'');
        v_shipper := (SELECT SHIPPER_NAME FROM MENDIX_APP.AGENTS.BILL_OF_LADING
        WHERE BL_ID = (SELECT BL_ID FROM MENDIX_APP.AGENTS.FRAUD_ALERT WHERE ALERT_ID = :v_alert_id LIMIT 1));
        v_step_start := CURRENT_TIMESTAMP();
        CALL MENDIX_APP.AGENTS.WORKFLOW_SANCTIONS_SCREEN(:v_shipper);
        v_step_ms := DATEDIFF(''millisecond'', :v_step_start, CURRENT_TIMESTAMP());
        INSERT INTO MENDIX_APP.AGENTS.WORKFLOW_AUDIT_LOG (WORKFLOW_NAME, STEP_NAME, STEP_ORDER, INPUT_PARAMS, OUTPUT_RESULT, EXECUTION_TIME_MS, STATUS)
        VALUES (''FULL_PIPELINE_V2'', ''SANCTIONS_SCREEN'', 3, :v_shipper, ''Completed'', :v_step_ms, ''SUCCESS'');
        v_step_start := CURRENT_TIMESTAMP();
        CALL MENDIX_APP.AGENTS.WORKFLOW_AUTO_REMEDIATE(:v_alert_id, :v_ai_action);
        v_step_ms := DATEDIFF(''millisecond'', :v_step_start, CURRENT_TIMESTAMP());
        INSERT INTO MENDIX_APP.AGENTS.WORKFLOW_AUDIT_LOG (WORKFLOW_NAME, STEP_NAME, STEP_ORDER, INPUT_PARAMS, OUTPUT_RESULT, EXECUTION_TIME_MS, STATUS)
        VALUES (''FULL_PIPELINE_V2'', ''AUTO_REMEDIATE'', 4, ''alert='' || :v_alert_id || '',action='' || :v_ai_action, ''Executed'', :v_step_ms, ''SUCCESS'');
        v_sap_result := ''{"status":"SKIPPED"}'';
        IF (:v_ai_action = ''CLEAR'') THEN
            SELECT BL_ID INTO :v_sap_bl_id FROM MENDIX_APP.AGENTS.FRAUD_ALERT WHERE ALERT_ID = :v_alert_id LIMIT 1;
            IF (:v_sap_bl_id IS NOT NULL) THEN
                v_step_start := CURRENT_TIMESTAMP();
                CALL MENDIX_APP.AGENTS.SAP_POST_FI_DOCUMENT(:v_sap_bl_id) INTO :v_sap_result;
                v_step_ms := DATEDIFF(''millisecond'', :v_step_start, CURRENT_TIMESTAMP());
                v_sap_posted := :v_sap_posted + 1;
                INSERT INTO MENDIX_APP.AGENTS.WORKFLOW_AUDIT_LOG (WORKFLOW_NAME, STEP_NAME, STEP_ORDER, INPUT_PARAMS, OUTPUT_RESULT, EXECUTION_TIME_MS, STATUS)
                VALUES (''FULL_PIPELINE_V2'', ''SAP_POST'', 5, ''bl_id='' || :v_sap_bl_id, :v_sap_result, :v_step_ms, ''SUCCESS'');
            END IF;
        END IF;
        v_processed := :v_processed + 1;
        v_alert_ids := IFF(:v_alert_ids = '''', TO_VARCHAR(:v_alert_id), :v_alert_ids || '','' || :v_alert_id);
        IF (:v_ai_action = ''BLOCK'') THEN v_blocked := :v_blocked + 1;
        ELSEIF (:v_ai_action = ''CLEAR'') THEN v_cleared := :v_cleared + 1;
        ELSE v_escalated := :v_escalated + 1; END IF;
        IF (:v_first_decision IS NULL) THEN v_first_decision := :v_ai_action; v_first_reason := :v_ai_reason; END IF;
    END LOOP;
    IF (:v_processed = 0) THEN
        INSERT INTO MENDIX_APP.AGENTS.WORKFLOW_AUDIT_LOG (WORKFLOW_NAME, STEP_NAME, STEP_ORDER, INPUT_PARAMS, OUTPUT_RESULT, EXECUTION_TIME_MS, STATUS)
        VALUES (''FULL_PIPELINE_V2'', ''AI_INVESTIGATE'', 2, ''no_open_alert'', ''SKIPPED'', 0, ''SKIPPED'');
        v_first_decision := ''NONE''; v_first_reason := ''No open alert in this run.'';
    END IF;
    v_elapsed_ms := DATEDIFF(''millisecond'', :v_start_time, CURRENT_TIMESTAMP());
