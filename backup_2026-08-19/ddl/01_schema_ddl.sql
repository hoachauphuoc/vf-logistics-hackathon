create or replace dynamic table MENDIX_APP.AGENTS.DT_CARRIER_PERFORMANCE(
	CARRIER_NAME,
	TOTAL_SHIPMENTS,
	AVG_CHARGES,
	TOTAL_REVENUE,
	AVG_WEIGHT_KGS,
	DELIVERED_COUNT,
	DELIVERY_SUCCESS_RATE_PCT
) target_lag = '5 minutes' refresh_mode = AUTO initialize = ON_CREATE warehouse = COMPUTE_WH
 as SELECT CARRIER_NAME, COUNT(*) as TOTAL_SHIPMENTS, ROUND(AVG(TOTAL_CHARGES), 2) as AVG_CHARGES, ROUND(SUM(TOTAL_CHARGES), 2) as TOTAL_REVENUE, ROUND(AVG(GROSS_WEIGHT_KGS), 2) as AVG_WEIGHT_KGS, SUM(CASE WHEN STATUS = 'Delivered' THEN 1 ELSE 0 END) as DELIVERED_COUNT, ROUND(SUM(CASE WHEN STATUS = 'Delivered' THEN 1 ELSE 0 END) * 100.0 / NULLIF(COUNT(*), 0), 2) as DELIVERY_SUCCESS_RATE_PCT FROM BILL_OF_LADING WHERE CARRIER_NAME IS NOT NULL GROUP BY CARRIER_NAME;
create or replace dynamic table MENDIX_APP.AGENTS.DT_ROUTE_ANALYTICS(
	ROUTE,
	ORIGIN_PORT,
	DEST_PORT,
	TOTAL_SHIPMENTS,
	AVG_FREIGHT_COST,
	AVG_WEIGHT_KGS,
	MIN_CHARGES,
	MAX_CHARGES
) target_lag = '5 minutes' refresh_mode = AUTO initialize = ON_CREATE warehouse = COMPUTE_WH
 as SELECT PORT_OF_LOADING_LOCODE || '_TO_' || PORT_OF_DISCHARGE_LOCODE as ROUTE, PORT_OF_LOADING_LOCODE as ORIGIN_PORT, PORT_OF_DISCHARGE_LOCODE as DEST_PORT, COUNT(*) as TOTAL_SHIPMENTS, ROUND(AVG(TOTAL_CHARGES), 2) as AVG_FREIGHT_COST, ROUND(AVG(GROSS_WEIGHT_KGS), 2) as AVG_WEIGHT_KGS, MIN(TOTAL_CHARGES) as MIN_CHARGES, MAX(TOTAL_CHARGES) as MAX_CHARGES FROM BILL_OF_LADING WHERE PORT_OF_LOADING_LOCODE IS NOT NULL AND PORT_OF_DISCHARGE_LOCODE IS NOT NULL GROUP BY PORT_OF_LOADING_LOCODE, PORT_OF_DISCHARGE_LOCODE;
create or replace dynamic table MENDIX_APP.AGENTS.DT_SHIPMENT_KPI(
	TOTAL_SHIPMENTS,
	SAP_POSTED,
	PENDING_REVIEW,
	IN_TRANSIT,
	DELIVERED,
	AVG_CHARGES_USD,
	TOTAL_REVENUE_USD,
	AVG_WEIGHT_KGS,
	LAST_BL_CREATED_AT,
	REFRESHED_AT
) target_lag = '1 minute' refresh_mode = AUTO initialize = ON_CREATE warehouse = COMPUTE_WH
 as SELECT COUNT(*) as TOTAL_SHIPMENTS, SUM(CASE WHEN STATUS = 'SAP_POSTED' THEN 1 ELSE 0 END) as SAP_POSTED, SUM(CASE WHEN STATUS = 'Pending_Review' THEN 1 ELSE 0 END) as PENDING_REVIEW, SUM(CASE WHEN STATUS = 'In_Transit' THEN 1 ELSE 0 END) as IN_TRANSIT, SUM(CASE WHEN STATUS = 'Delivered' THEN 1 ELSE 0 END) as DELIVERED, ROUND(AVG(TOTAL_CHARGES), 2) as AVG_CHARGES_USD, ROUND(SUM(TOTAL_CHARGES), 2) as TOTAL_REVENUE_USD, ROUND(AVG(GROSS_WEIGHT_KGS), 2) as AVG_WEIGHT_KGS, MAX(CREATED_AT) as LAST_BL_CREATED_AT, CURRENT_TIMESTAMP() as REFRESHED_AT FROM BILL_OF_LADING;
