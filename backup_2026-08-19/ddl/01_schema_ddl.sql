CREATE OR REPLACE PROCEDURE MENDIX_APP.AGENTS.WORKFLOW_AUTO_REMEDIATE("P_ALERT_ID" NUMBER(38,0), "P_ACTION" VARCHAR)
RETURNS VARCHAR
LANGUAGE SQL
COMMENT='Automated remediation: applies BLOCK/ESCALATE/CLEAR and records AI decision reason.'
EXECUTE AS CALLER
AS '
DECLARE v_bl_id NUMBER; v_bl_number VARCHAR; v_result VARCHAR; v_ai_reason VARCHAR; v_note VARCHAR;
BEGIN
    SELECT BL_ID, NVL(AI_DECISION_REASON, ''No AI reason recorded'') INTO :v_bl_id, :v_ai_reason
    FROM MENDIX_APP.AGENTS.FRAUD_ALERT WHERE ALERT_ID = :P_ALERT_ID;
    SELECT BL_NUMBER INTO :v_bl_number FROM MENDIX_APP.AGENTS.BILL_OF_LADING WHERE BL_ID = :v_bl_id;
    CASE UPPER(:P_ACTION)
        WHEN ''BLOCK'' THEN
            v_note := ''AUTO-BLOCKED by AI decision. Reason: '' || :v_ai_reason;
            UPDATE MENDIX_APP.AGENTS.BILL_OF_LADING SET STATUS = ''BLOCKED'', FRAUD_CHECK_PASSED = FALSE WHERE BL_ID = :v_bl_id;
            UPDATE MENDIX_APP.AGENTS.FRAUD_ALERT SET STATUS = ''RESOLVED'', RESOLVED_AT = CURRENT_TIMESTAMP(), RESOLUTION_NOTES = LEFT(:v_note, 2000) WHERE ALERT_ID = :P_ALERT_ID;
            INSERT INTO MENDIX_APP.AGENTS.NOTIFICATION_LOG (NOTIFICATION_TYPE, RECIPIENT, SUBJECT, BODY, STATUS)
            VALUES (''FRAUD_BLOCK'', ''compliance@vflogistics.com'', ''Shipment Blocked'', ''BLOCKED: '' || :v_bl_number || '' - '' || :v_ai_reason, ''SENT'');
            v_result := ''Shipment '' || :v_bl_number || '' BLOCKED.'';
        WHEN ''ESCALATE'' THEN
            v_note := ''ESCALATED by AI decision. Reason: '' || :v_ai_reason;
            UPDATE MENDIX_APP.AGENTS.BILL_OF_LADING SET STATUS = ''Pending_Review'' WHERE BL_ID = :v_bl_id;
            UPDATE MENDIX_APP.AGENTS.FRAUD_ALERT SET STATUS = ''ESCALATED'', RESOLUTION_NOTES = LEFT(:v_note, 2000) WHERE ALERT_ID = :P_ALERT_ID;
            INSERT INTO MENDIX_APP.AGENTS.NOTIFICATION_LOG (NOTIFICATION_TYPE, RECIPIENT, SUBJECT, BODY, STATUS)
            VALUES (''FRAUD_ESCALATE'', ''compliance@vflogistics.com'', ''Alert Escalated'', ''Alert #'' || :P_ALERT_ID || '' on '' || :v_bl_number || '' - '' || :v_ai_reason, ''SENT'');
            v_result := ''Alert #'' || :P_ALERT_ID || '' ESCALATED.'';
        WHEN ''CLEAR'' THEN
            v_note := ''CLEARED by AI - no fraud. Reason: '' || :v_ai_reason;
            UPDATE MENDIX_APP.AGENTS.FRAUD_ALERT SET STATUS = ''RESOLVED'', RESOLVED_AT = CURRENT_TIMESTAMP(), RESOLUTION_NOTES = LEFT(:v_note, 2000) WHERE ALERT_ID = :P_ALERT_ID;
            UPDATE MENDIX_APP.AGENTS.BILL_OF_LADING SET FRAUD_CHECK_PASSED = TRUE WHERE BL_ID = :v_bl_id;
            v_result := ''Alert #'' || :P_ALERT_ID || '' CLEARED. Shipment approved.'';
        ELSE v_result := ''ERROR: Unknown action.'';
    END CASE;
    RETURN ''{"workflow":"AUTO_REMEDIATE","alert_id":'' || :P_ALERT_ID || '',"action":"'' || :P_ACTION || ''","result":"'' || :v_result || ''"}'';
END
';
CREATE OR REPLACE PROCEDURE MENDIX_APP.AGENTS.WORKFLOW_DETECT_AND_ACT("P_QUEUE_LIMIT" NUMBER(38,0) DEFAULT 100)
RETURNS VARCHAR
LANGUAGE SQL
COMMENT='Automated fraud/compliance detection with data-derived thresholds. Excludes Pending_Review/DRAFT records.'
EXECUTE AS CALLER
AS '
DECLARE
    v_p99_charges FLOAT; v_p99_weight FLOAT; v_p95_cpk FLOAT; v_median_cpk FLOAT;
    v_new_alerts NUMBER DEFAULT 0; v_high_severity NUMBER DEFAULT 0; v_actions_taken NUMBER DEFAULT 0;
    v_cap NUMBER DEFAULT 8; v_queue_open NUMBER DEFAULT 0; v_throttled BOOLEAN DEFAULT FALSE;
BEGIN
    SELECT COUNT(*) INTO :v_queue_open FROM MENDIX_APP.AGENTS.FRAUD_ALERT
    WHERE STATUS = ''OPEN'' AND SEVERITY IN (''HIGH'', ''MEDIUM'') AND BL_ID IS NOT NULL AND DETECTED_AT >= DATEADD(day, -7, CURRENT_TIMESTAMP()) /* QUEUE_WINDOW_DAYS = 7 */;
    SELECT PERCENTILE_CONT(0.99) WITHIN GROUP (ORDER BY TOTAL_CHARGES),
           PERCENTILE_CONT(0.99) WITHIN GROUP (ORDER BY GROSS_WEIGHT_KGS),
           PERCENTILE_CONT(0.95) WITHIN GROUP (ORDER BY TOTAL_CHARGES / NULLIF(GROSS_WEIGHT_KGS,0)),
           MEDIAN(TOTAL_CHARGES / NULLIF(GROSS_WEIGHT_KGS,0))
    INTO :v_p99_charges, :v_p99_weight, :v_p95_cpk, :v_median_cpk
    FROM MENDIX_APP.AGENTS.BILL_OF_LADING
    WHERE TOTAL_CHARGES IS NOT NULL AND GROSS_WEIGHT_KGS > 0 AND STATUS NOT IN (''Pending_Review'', ''DRAFT'');
    v_throttled := (:v_queue_open >= :P_QUEUE_LIMIT); /* This gate used to wrap every detection rule in its ELSE branch, so a saturated queue skipped all of them and a backlog of MEDIUM alerts could hide a HIGH-severity fraud. It now only records that the queue is saturated; each rule below carries its own severity guard. The IF is kept as a deliberately-always-false branch so the existing ELSE / END IF structure stays valid without restructuring five INSERT statements. */ IF (FALSE) THEN v_throttled := :v_throttled;
    ELSE
        INSERT INTO MENDIX_APP.AGENTS.FRAUD_ALERT (ALERT_TYPE, SEVERITY, DESCRIPTION, BL_ID, STATUS, CREATED_AT, DETECTED_AT)
        SELECT ''COST_PER_KG_ANOMALY'',
            CASE WHEN TOTAL_CHARGES / GROSS_WEIGHT_KGS > 10 * :v_median_cpk THEN ''HIGH'' ELSE ''MEDIUM'' END,
            ''Cost/kg $'' || ROUND(TOTAL_CHARGES / GROSS_WEIGHT_KGS, 4) || '' vs median $'' || ROUND(:v_median_cpk, 4) || '' on '' || BL_NUMBER,
            BL_ID, ''OPEN'', CURRENT_TIMESTAMP(), CURRENT_TIMESTAMP()
        FROM MENDIX_APP.AGENTS.BILL_OF_LADING b
        WHERE GROSS_WEIGHT_KGS > 0 AND TOTAL_CHARGES IS NOT NULL
          AND TOTAL_CHARGES / GROSS_WEIGHT_KGS > 5 * :v_median_cpk AND (:v_throttled = FALSE OR TOTAL_CHARGES / GROSS_WEIGHT_KGS > 10 * :v_median_cpk)
          AND NOT EXISTS (SELECT 1 FROM MENDIX_APP.AGENTS.FRAUD_ALERT a WHERE a.BL_ID = b.BL_ID)
        ORDER BY TOTAL_CHARGES / GROSS_WEIGHT_KGS DESC LIMIT :v_cap;
        v_new_alerts := SQLROWCOUNT;
        INSERT INTO MENDIX_APP.AGENTS.FRAUD_ALERT (ALERT_TYPE, SEVERITY, DESCRIPTION, BL_ID, STATUS, CREATED_AT, DETECTED_AT)
        SELECT ''HIGH_VALUE_ANOMALY'',
            CASE WHEN GROSS_WEIGHT_KGS > 0 AND TOTAL_CHARGES / GROSS_WEIGHT_KGS > 10 * :v_median_cpk THEN ''HIGH'' ELSE ''MEDIUM'' END,
            ''Charges $'' || TOTAL_CHARGES || '' exceed p99 $'' || ROUND(:v_p99_charges) || '' on '' || BL_NUMBER,
            BL_ID, ''OPEN'', CURRENT_TIMESTAMP(), CURRENT_TIMESTAMP()
        FROM MENDIX_APP.AGENTS.BILL_OF_LADING b
        WHERE TOTAL_CHARGES > :v_p99_charges AND (:v_throttled = FALSE OR (GROSS_WEIGHT_KGS > 0 AND TOTAL_CHARGES / GROSS_WEIGHT_KGS > 10 * :v_median_cpk))
          AND NOT EXISTS (SELECT 1 FROM MENDIX_APP.AGENTS.FRAUD_ALERT a WHERE a.BL_ID = b.BL_ID)
        ORDER BY TOTAL_CHARGES DESC LIMIT :v_cap;
        v_new_alerts := :v_new_alerts + SQLROWCOUNT;
        INSERT INTO MENDIX_APP.AGENTS.FRAUD_ALERT (ALERT_TYPE, SEVERITY, DESCRIPTION, BL_ID, STATUS, CREATED_AT, DETECTED_AT)
        SELECT ''WEIGHT_ANOMALY'', ''MEDIUM'',
            ''Weight '' || GROSS_WEIGHT_KGS || ''kg exceeds p99 '' || ROUND(:v_p99_weight) || ''kg on '' || BL_NUMBER,
            BL_ID, ''OPEN'', CURRENT_TIMESTAMP(), CURRENT_TIMESTAMP()
        FROM MENDIX_APP.AGENTS.BILL_OF_LADING b
        WHERE GROSS_WEIGHT_KGS > :v_p99_weight AND :v_throttled = FALSE
          AND NOT EXISTS (SELECT 1 FROM MENDIX_APP.AGENTS.FRAUD_ALERT a WHERE a.BL_ID = b.BL_ID)
        ORDER BY GROSS_WEIGHT_KGS DESC LIMIT :v_cap;
        v_new_alerts := :v_new_alerts + SQLROWCOUNT;
        INSERT INTO MENDIX_APP.AGENTS.FRAUD_ALERT (ALERT_TYPE, SEVERITY, DESCRIPTION, BL_ID, STATUS, CREATED_AT, DETECTED_AT)
        SELECT ''SUSPICIOUS_PARTY'', ''HIGH'',
            ''Suspicious counterparty on '' || BL_NUMBER || '': '' || SHIPPER_NAME || '' -> '' || NVL(CONSIGNEE_NAME, ''(none)''),
            BL_ID, ''OPEN'', CURRENT_TIMESTAMP(), CURRENT_TIMESTAMP()
        FROM MENDIX_APP.AGENTS.BILL_OF_LADING b
        WHERE (UPPER(SHIPPER_NAME) LIKE ''%SUSPICIOUS%'' OR UPPER(CONSIGNEE_NAME) LIKE ''%SHELL CORP%'' OR UPPER(SHIPPER_NAME) LIKE ''%UNKNOWN%'')
          AND NOT EXISTS (SELECT 1 FROM MENDIX_APP.AGENTS.FRAUD_ALERT a WHERE a.BL_ID = b.BL_ID) LIMIT :v_cap;
        v_new_alerts := :v_new_alerts + SQLROWCOUNT;
        INSERT INTO MENDIX_APP.AGENTS.FRAUD_ALERT (ALERT_TYPE, SEVERITY, DESCRIPTION, BL_ID, STATUS, CREATED_AT, DETECTED_AT)
        SELECT ''DOCUMENT_QUALITY'', CASE WHEN AI_CONFIDENCE_SCORE <= 50 THEN ''HIGH'' ELSE ''MEDIUM'' END,
            ''AI confidence '' || AI_CONFIDENCE_SCORE::VARCHAR || ''/100 on '' || BL_NUMBER,
            BL_ID, ''OPEN'', CURRENT_TIMESTAMP(), CURRENT_TIMESTAMP()
        FROM MENDIX_APP.AGENTS.BILL_OF_LADING b
        WHERE AI_CONFIDENCE_SCORE IS NOT NULL AND AI_CONFIDENCE_SCORE < 85 AND (:v_throttled = FALSE OR AI_CONFIDENCE_SCORE <= 50)
          AND NOT EXISTS (SELECT 1 FROM MENDIX_APP.AGENTS.FRAUD_ALERT a WHERE a.BL_ID = b.BL_ID) LIMIT :v_cap;
        v_new_alerts := :v_new_alerts + SQLROWCOUNT;
    END IF;
    SELECT COUNT(*) INTO :v_high_severity FROM MENDIX_APP.AGENTS.FRAUD_ALERT WHERE SEVERITY = ''HIGH'' AND STATUS = ''OPEN'';
    UPDATE MENDIX_APP.AGENTS.BILL_OF_LADING SET STATUS = ''Pending_Review'', FRAUD_CHECK_PASSED = FALSE
    WHERE BL_ID IN (SELECT BL_ID FROM MENDIX_APP.AGENTS.FRAUD_ALERT WHERE SEVERITY = ''HIGH'' AND STATUS = ''OPEN'' AND BL_ID IS NOT NULL)
      AND STATUS NOT IN (''Pending_Review'', ''BLOCKED'');
    v_actions_taken := SQLROWCOUNT;
    INSERT INTO MENDIX_APP.AGENTS.NOTIFICATION_LOG (NOTIFICATION_TYPE, RECIPIENT, SUBJECT, BODY, STATUS)
    SELECT ''WORKFLOW_RUN'', ''system'', IFF(:v_throttled, ''Detection throttled'', ''Detection completed''),
           ''New alerts: '' || :v_new_alerts || ''. HIGH open: '' || :v_high_severity, ''SENT'';
    RETURN ''{"workflow":"DETECT_AND_ACT","throttled":'' || IFF(:v_throttled, ''true'', ''false'')
        || '',"medium_suppressed":'' || IFF(:v_throttled, ''true'', ''false'') || '',"new_alerts":'' || :v_new_alerts || '',"high_severity_open":'' || :v_high_severity
        || '',"shipments_flagged":'' || :v_actions_taken || ''}'';
END
';
CREATE OR REPLACE PROCEDURE MENDIX_APP.AGENTS.WORKFLOW_FULL_PIPELINE()
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS CALLER
AS 'DECLARE v_scan_result VARCHAR; v_alert_id NUMBER;
BEGIN
    CALL MENDIX_APP.AGENTS.WORKFLOW_DETECT_AND_ACT();
    v_scan_result := SQLROWCOUNT || '' rules executed'';
    SELECT ALERT_ID INTO :v_alert_id FROM MENDIX_APP.AGENTS.FRAUD_ALERT
    WHERE SEVERITY = ''HIGH'' AND STATUS = ''OPEN'' ORDER BY CREATED_AT DESC LIMIT 1;
